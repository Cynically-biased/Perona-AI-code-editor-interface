const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('desk', {
  windowControl: action => ipcRenderer.invoke('window-control', action),
  loadGameEngine: id => ipcRenderer.invoke('game-engine-load', id),
  chooseGameEngine: id => ipcRenderer.invoke('game-engine-choose', id),
  saveGameEngine: (id, profile) => ipcRenderer.invoke('game-engine-save', id, profile),
  launchGameEngine: (id, action) => ipcRenderer.invoke('game-engine-launch', id, action),
  stopGameEngine: id => ipcRenderer.invoke('game-engine-stop', id),
  copyTerminalText: text => ipcRenderer.invoke('terminal-copy', text),
  readTerminalClipboard: () => ipcRenderer.invoke('terminal-paste'),
  appUpdateStatus: () => ipcRenderer.invoke('app-update-status'),
  checkAppUpdate: (download = true) => ipcRenderer.invoke('app-update-check', download),
  earlierAppVersions: () => ipcRenderer.invoke('app-update-versions'),
  downloadAppDowngrade: version => ipcRenderer.invoke('app-update-downgrade', version),
  installAppUpdate: () => ipcRenderer.invoke('app-update-install'),
  onAppUpdate: callback => ipcRenderer.on('app-update-status', (_event, status) => callback(status)),
  onConfirmWindowClose: callback => ipcRenderer.on('confirm-window-close', () => callback()),
  onWindowMaximized: callback => ipcRenderer.on('window-maximized', (_event, maximized) => callback(maximized)),
  onWindowMoved: callback => ipcRenderer.on('window-moved', () => callback()),
  addNewProject: (id, agent, name, preferred) => ipcRenderer.invoke('workspace-add-new-project', id, agent, name, preferred),
  openProject: (id, agent, name, preferred) => ipcRenderer.invoke('workspace-open-project', id, agent, name, preferred),
  pickSettingsFolder: preferred => ipcRenderer.invoke('settings-pick-folder', preferred),
  setInterfaceZoom: percent => ipcRenderer.invoke('settings-zoom', percent),
  onInterfaceZoomStep: callback => ipcRenderer.on('settings-zoom-step', (_event, direction) => callback(direction)),
  addDroppedProject: (id, agent, name, file) =>
    ipcRenderer.invoke('workspace-add-dropped-project', id, agent, name, webUtils.getPathForFile(file)),
  importProjectFiles: (id, folder, files, replacement) =>
    ipcRenderer.invoke('project-import-files', id, folder, files.map(file => webUtils.getPathForFile(file)), replacement),
  pickChatFolder: (id, agent, currentFolder) => ipcRenderer.invoke('pick-chat-folder', id, agent, currentFolder),
  start: (id, agent, cols, rows, usePickedFolder, chatId, name) =>
    ipcRenderer.invoke('start-chat', id, agent, cols, rows, usePickedFolder, chatId, name),
  savedWorkspace: () => ipcRenderer.invoke('workspace-load'),
  addProjectChat: (sourceChat, sourceProject, id, agent, name) =>
    ipcRenderer.invoke('workspace-add-project-chat', sourceChat, sourceProject, id, agent, name),
  removeProjectChat: (chat, id) => ipcRenderer.invoke('workspace-remove-project-chat', chat, id),
  saveProjectDock: (chat, project, layout) =>
    ipcRenderer.invoke('workspace-save-project-dock', chat, project, layout),
  selectWorkspace: (chat, project, view, layout, session) =>
    ipcRenderer.invoke('workspace-select', chat, project, view, layout, session),
  renameWorkspace: (chat, name) => ipcRenderer.invoke('workspace-rename', chat, name),
  removeWorkspace: chat => ipcRenderer.invoke('workspace-remove', chat),
  previewSuggest: id => ipcRenderer.invoke('preview-suggest', id),
  previewChoosePlaytest: id => ipcRenderer.invoke('preview-choose-playtest', id),
  previewStartPlaytest: (id, options) => ipcRenderer.invoke('preview-start-playtest', id, options),
  previewPlaytestLayout: (id, bounds) => ipcRenderer.invoke('preview-playtest-layout', id, bounds),
  previewStopPlaytest: id => ipcRenderer.invoke('preview-stop-playtest', id),
  onPreviewPlaytestEnded: callback => ipcRenderer.on('preview-playtest-ended', (_event, ...args) => callback(...args)),
  previewShow: (id, url) => ipcRenderer.invoke('preview-show', id, url),
  previewHide: () => ipcRenderer.invoke('preview-hide'),
  previewStopGame: id => ipcRenderer.invoke('preview-stop-game', id),
  previewReload: id => ipcRenderer.invoke('preview-reload', id),
  previewBack: id => ipcRenderer.invoke('preview-back', id),
  onPreview: callback => ipcRenderer.on('preview-update', (_event, ...args) => callback(...args)),
  xamppStatus: () => ipcRenderer.invoke('xampp-status'),
  xamppControl: (id, action) => ipcRenderer.invoke('xampp-control', id, action),
  xamppLog: id => ipcRenderer.invoke('xampp-log', id),
  xamppAdmin: id => ipcRenderer.invoke('xampp-admin', id),
  xamppNetstat: () => ipcRenderer.invoke('xampp-netstat'),
  xamppUtility: action => ipcRenderer.invoke('xampp-utility', action),
  xamppConfig: (id, relative) => ipcRenderer.invoke('xampp-config', id, relative),
  xamppConfigSave: (id, relative, revision, text) => ipcRenderer.invoke('xampp-config-save', id, relative, revision, text),
  history: (id, candidate, idle) => ipcRenderer.invoke('session-history', id, candidate, idle),
  files: (id, relative) => ipcRenderer.invoke('project-list', id, relative),
  preview: (id, relative) => ipcRenderer.invoke('project-preview', id, relative),
  save: (id, relative, revision, text) => ipcRenderer.invoke('project-save', id, relative, revision, text),
  createEntry: (id, relative, type) => ipcRenderer.invoke('project-create', id, relative, type),
  moveEntry: (id, relative, target) => ipcRenderer.invoke('project-move', id, relative, target),
  removeEntry: (id, relative, directory) => ipcRenderer.invoke('project-remove', id, relative, directory),
  changes: id => ipcRenderer.invoke('project-changes', id),
  gitStatus: id => ipcRenderer.invoke('git-status', id),
  cloneRepository: (id, agent, name, url, preferred) => ipcRenderer.invoke('git-clone', id, agent, name, url, preferred),
  gitTrackedPaths: id => ipcRenderer.invoke('git-tracked-paths', id),
  gitAction: (id, action, data) => ipcRenderer.invoke('git-action', id, action, data),
  gitCreatePage: provider => ipcRenderer.invoke('git-create-page', provider),
  input: (id, data) => ipcRenderer.invoke('chat-input', id, data),
  chatScrollback: (id, end) => ipcRenderer.invoke('chat-scrollback', id, end),
  newlineChat: id => ipcRenderer.invoke('chat-newline', id),
  resize: (id, cols, rows) => ipcRenderer.invoke('chat-resize', id, cols, rows),
  close: id => ipcRenderer.invoke('close-chat', id),
  onData: callback => ipcRenderer.on('chat-data', (_event, ...args) => callback(...args)),
  onExit: callback => ipcRenderer.on('chat-exit', (_event, ...args) => callback(...args)),
  updateAgent: (id, cols, rows, thread) => ipcRenderer.invoke('update-chat-agent', id, cols, rows, thread),
  onAgentUpdate: callback => ipcRenderer.on('chat-update-state', (_event, ...args) => callback(...args)),
  agentUsage: () => ipcRenderer.invoke('agent-usage'),
  startProjectShell: (...args) => ipcRenderer.invoke('project-shell-start', ...args),
  installFish: () => ipcRenderer.invoke('project-shell-install-fish'),
  projectShellInput: (...args) => ipcRenderer.invoke('project-shell-input', ...args),
  projectShellResize: (...args) => ipcRenderer.invoke('project-shell-resize', ...args),
  onProjectShellData: callback => ipcRenderer.on('project-shell-data', (_event, ...args) => callback(...args)),
  onProjectShellExit: callback => ipcRenderer.on('project-shell-exit', (_event, ...args) => callback(...args))
});
